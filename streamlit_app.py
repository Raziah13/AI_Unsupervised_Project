    f.write("            st.subheader('Segment Summarization')\n")
    f.write("            \n")
    f.write("            segment_summary = []\n")
    f.write("            for cluster in range(5):\n")
    f.write("                cluster_data = st.session_state.kmeans_df[st.session_state.kmeans_df['Cluster'] == cluster]\n")
