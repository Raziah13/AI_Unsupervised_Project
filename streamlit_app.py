    f.write("            fig, axes = plt.subplots(1, 2, figsize=(14, 5))\n")
    f.write("            \n")
    f.write("            axes[0].scatter(X_pca[:, 0], X_pca[:, 1], c=st.session_state.kmeans_labels, cmap='viridis', s=50, alpha=0.6)\n")
